#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const bundle = await build({ stdin: {
  contents: "export * from './services/revamp/curve/difficultyCurve.ts'; export * from './services/revamp/curve/authorCampaign.mjs';",
  resolveDir: root, loader: 'ts',
}, bundle: true, platform: 'node', format: 'esm', write: false });
const { missionCurve, spawnThreat, waveThreat, authorRevampCampaign, authorEscalationBase } = await import(
  `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const campaignPath = resolve(root, 'game-config/campaign.json');
const escalationPath = resolve(root, 'game-config/campaign-escalation-base.json');
let campaign = JSON.parse(await readFile(campaignPath, 'utf8'));
const escalation = JSON.parse(await readFile(escalationPath, 'utf8'));
if (process.argv.includes('--write')) {
  campaign = authorRevampCampaign(campaign);
  await writeFile(campaignPath, `${JSON.stringify(campaign, null, 2)}\n`);
  await writeFile(escalationPath, `${JSON.stringify(authorEscalationBase(campaign, escalation), null, 2)}\n`);
}
if (process.argv.includes('--check')) {
  if (JSON.stringify(campaign) !== JSON.stringify(authorRevampCampaign(campaign))) throw new Error('Campaign differs from deterministic authoring source; run --write.');
  if (JSON.stringify(escalation) !== JSON.stringify(authorEscalationBase(campaign, escalation))) throw new Error('Escalation base differs from authoring source; run --write.');
}
const fmt = (n) => Number(n).toFixed(2);
const sectors = new Set(campaign.sectors.slice(0, 3).map((sector) => sector.id));
const nodes = campaign.campaignGraph.nodes.filter((node) => sectors.has(node.sectorId) && node.mainPath)
  .sort((a, b) => a.depth - b.depth);
const rows = [];
const waveRows = [];
for (const node of nodes) {
  const level = campaign.levels.find((level) => level.id === node.missionDefinitionId);
  const curve = missionCurve(node.depth);
  const spawns = level.waves.flatMap((wave) => wave.events.filter((event) => event.kind === 'spawn'));
  const threats = level.waves.filter(wave => wave.events.some(event => event.kind === 'spawn')).map(wave => waveThreat(wave.events, campaign.enemyRoles));
  const ttks = spawns.flatMap((event) => event.enemies.map((enemy) => enemy.health / curve.expectedDps));
  rows.push(`| ${String(node.depth).padStart(2, '0')} · ${level.name} | ${fmt(curve.threat)} | ${fmt(threats.reduce((a, b) => a + b, 0) / threats.length)} | ${curve.expectedPower} | ${fmt(Math.min(...ttks))}–${fmt(Math.max(...ttks))} s | ${curve.afterBoss ? '−10% sector breath' : node.depth === 1 ? '60–90 s target' : '+7%'} |`);
  for (const wave of level.waves) {
    const boss = wave.events.find((event) => event.kind === 'boss');
    const mini = boss && campaign.miniBosses.find((mini) => mini.bossId === boss.bossId);
    const bossNote = !boss ? '—' : mini ? `${mini.threatCost} mini-boss (separate)` : `${boss.bossId} (separate boss runtime)`;
    waveRows.push(`| ${node.depth}.${wave.order} | ${wave.rhythm} | ${fmt(waveThreat(wave.events, campaign.enemyRoles))} | ${bossNote} |`);
  }
}
const text = `# Revamp I difficulty curve

Generated by \`node tools-revamp/curve-report.mjs\`; apply campaign and report with \`--write\`, verify reproducibility with \`--check\`.

## Dense formation model

Each regular wave contains 30–34 hulls: a mirrored 28–32-ship Orbit Wing grid and two named special enemies from the B roster. Six columns settle across the upper playfield, breathe together, then peel into announced dives. The first sector uses top swoops, loops and S-curves before side pincers. Existing pixel art is reused at an authored 0.68–0.72 hull scale; collision and visuals share that scale. No art files are replaced.

Regular authored pressure is **Σ(count × weighted role cost × max(0.25, 3 / fire interval) × burst count)**. Slower fire can now reduce pressure instead of being clamped to full threat: density and danger are separate controls. The mission target is the mean complete regular wave, including its two specials. It starts at 24, rises 7% within each sector, and resets 10% after the boss: 24 × (1.07^4 × 0.90)^(sector−1) × 1.07^(slot−1). Optional routes use graph depth. Three-wave rhythms average 0.90 / 1.10 / 1.00; two-wave boss lead-ins average 0.90 / 1.10. Sectors 1–3 share the generator to avoid an abrupt density collapse after the opening sector; later authored sectors remain intact.

The index is an authoring estimate. The live grid also has a shared staggered firing clock: one gun every 66 frames in Mission 1, gradually reducing to a 28-frame minimum. Each hull retains its authored cooldown. Mission 1 uses slow 1.75 px/tick bullets; later missions add 0.065 px/tick. Specials retain their telegraphs and authored shot speeds. The shared hostile cap, entry grace, travel, deaths and dive selection reduce actual output. This is not a claim of 7% more bullets or deaths.

Expected power is 1000 × 1.045^(mission−1), with estimated focused DPS of 4.0 × power/1000. Ordinary grid hulls use 0.4-second focused TTK; special roles retain 0.48–1.10 seconds. Shield Bearers expose their hull for 1.5 seconds after each 2.5-second guard, so a frontal pilot always has an observable damage window. Contact damage remains one. Starting and wave difficulty multipliers stay one; paid upgrades are never assumed.

## Mission targets

| Mission | Target / wave | Authored / wave | Expected power | Focused TTK | Transition |
|---|---:|---:|---:|---:|---|
${rows.join('\n')}

## Authored per-wave pressure

| Mission.wave | Rhythm | Regular pressure | Separate encounter |
|---|---|---:|---|
${waveRows.join('\n')}

## Pacing and fairness

Mission 1 uses two full grids followed by Peer Reviewer in a separate wave. The first enemy is visible within the opening second, the first guaranteed power drop is at six seconds, every later grid provides another power pickup, and the second provides a magnet. Boss-free opening waves allow the slim tutorial to dismiss before the encounter. Other ordinary missions use three grids, checkpoint missions two grids plus their mini-boss, and major missions two grids plus the existing boss mechanics. The 60–90-second target is verified through actual 60 Hz autoplay, not by summing scheduling windows. Boss health is an independent encounter knob; the first sector's boss is 160 HP and Peer Reviewer 110 HP plus its breakable eight-HP shield.

The final six surviving hulls regroup toward the center through the existing 42-frame eased slot transition after 15 combat seconds, then hold and shoot. This keeps an isolated edge hull from adding a long empty chase. No enemy is despawned or awarded as a free kill. Authored 0.133-second grid releases bypass legacy spawn-pressure scaling; side entries still receive their full 0.8-second warning. The same admission, spawn clock, fixed 390×844 world and 60 Hz simulation run under mobile, desktop and reduced rendering quality.

Run \`node tools-revamp/measure-opening.mjs --output /tmp/I-opening.json\` for baseline-loadout normal-damage timings, and add \`--god\` for coverage only. Reports include per-second density, holding/diving, bullets, kills, damage sources and completion. Human dodging and device GPU performance are separate checks. Rendered screenshots and clips are listed in REVAMP_NOTES_I.md.

## Authoring knobs and verification

- \`services/revamp/curve/authorCampaign.mjs\`: hull counts, grid slots, entry paths, special pairs, power drops, wave count and encounter HP.
- \`services/revamp/curve/difficultyCurve.ts\`: pressure growth/reset and expected power/TTK.
- \`services/revamp/formations/DenseFormationFire.ts\`: staggered grid fire and final-hull regroup.
- \`services/revamp/enemies/EnemyBehaviorRuntime.ts\`: entry grace, special telegraphs, plate recovery and shared bullet caps.
- \`node tools-revamp/validate-campaign.mjs\` validates all 60 missions. \`node --test tests-revamp/B/*.test.mjs tests-revamp/I/opening-pacing.test.mjs\` checks curve, spawns, combat, pacing and device parity.

Generated escalation baselines are refreshed with the campaign; removed-wave keys are pruned so earlier density passes cannot double the new cohorts.
`;
console.log(text);
if (process.argv.includes('--write')) await writeFile(resolve(root, 'docs/revamp/difficulty-curve.md'), text);
